function Logo({
  className,
  size = "md",
  type = "logomarca",
  version = "gradiente",
  brand = true,
}: LogoProps) {
  const prefix = useId().replace(/:/g, "");
  const isSimbolo = type === "simbolo";
  const sizes = isSimbolo ? SIMBOLO_SIZES[size] : LOGOMARCA_SIZES[size];
  const viewBox = isSimbolo ? "0 0 31.5 36.7" : "0 0 160 36.6075";

  const isLight = version === "clara";
  const isDark = version === "escura";
  const isFlat = version === "flat";
  const isGradient = version === "gradiente";

  let textFill = DARK;
  let seedFill = DARK;
  let fruitMode: "gradient" | "flat" | "mono" = "gradient";
  let monoColor = DARK;

  if (isGradient) {
    fruitMode = "gradient";
  } else if (isFlat) {
    fruitMode = "flat";
  } else if (isLight) {
    textFill = WHITE;
    fruitMode = brand ? "gradient" : "mono";
    seedFill = brand ? DARK : WHITE;
    monoColor = WHITE;
  } else if (isDark) {
    fruitMode = brand ? "gradient" : "mono";
    monoColor = DARK;
  }

  return (
    <svg
      width={sizes.w}
      height={sizes.h}
      viewBox={viewBox}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={cn("select-none", className)}
      role="img"
      aria-label="Manga"
    >
      {fruitMode === "gradient" && <GradientDefs prefix={prefix} />}

      {/* Symbol: seed + fruit */}
      <g>
        <path d={SEED_PATH} fill={seedFill} />
        {fruitMode === "gradient" && <FruitGradient prefix={prefix} />}
        {fruitMode === "flat" && <path d={FRUIT_PATH} fill={PRIMARY} />}
        {fruitMode === "mono" && <path d={FRUIT_PATH} fill={monoColor} />}
      </g>

      {/* Text: "manga" (logomarca only) */}
      {!isSimbolo &&
        TEXT_PATHS.map((d, i) => <path key={i} d={d} fill={textFill} />)}
    </svg>
  );
}

