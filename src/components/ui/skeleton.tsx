import { cn } from "@/lib/utils/cn";

interface SkeletonProps {
  className?: string;
}

function Skeleton({ className }: SkeletonProps) {
  return (
    <div
      className={cn(
        "animate-pulse rounded-lg bg-neutral-200",
        className
      )}
    />
  );
}

function SkeletonText({ className }: SkeletonProps) {
  return (
    <div className={cn("space-y-2", className)}>
      <Skeleton className="h-4 w-full" />
      <Skeleton className="h-4 w-3/4" />
    </div>
  );
}

function SkeletonCircle({ className }: SkeletonProps) {
  return (
    <Skeleton className={cn("size-10 rounded-full", className)} />
  );
}

export { Skeleton, SkeletonText, SkeletonCircle, type SkeletonProps };
